pub fn decode_block(llr: &[f64], iters: usize) -> Result<[u8; N], &'static str> {
    if llr.len() != N {
        return Err("LDPC block must be 128 LLRs");
    }
    let ch = llr;
    let mut c2v = [[0.0_f64; DC]; M];
    let mut v2c = [[0.0_f64; DC]; M];
    let mut hard = [0u8; N];
    for v in 0..N {
        hard[v] = u8::from(ch[v] < 0.0);
    }
    let n_iters = iters;
    for _ in 0..n_iters {
        for v in 0..N {
            let mut total = ch[v];
            for j in 0..DV {
                let c = COL_IDX[v][j];
                total += c2v[c][COL_EDGE[v][j]];
            }
            for j in 0..DV {
                let c = COL_IDX[v][j];
                let e = COL_EDGE[v][j];
                v2c[c][e] = total - c2v[c][e];
            }
        }
        for c in 0..M {
            let incoming = v2c[c];
            for i in 0..DC {
                let mut sign = 1.0;
                let mut mag = f64::INFINITY;
                for k in 0..DC {
                    if k == i {
                        continue;
                    }
                    let x = incoming[k];
                    let s = if x < 0.0 { -1.0 } else { 1.0 };
                    sign *= s;
                    let a = x.abs();
                    if a < mag {
                        mag = a;
                    }
                }
                c2v[c][i] = MS_SCALE * sign * mag;
            }
        }
        let mut ok = true;
        for v in 0..N {
            let mut posterior = ch[v];
            for j in 0..DV {
                let c = COL_IDX[v][j];
                posterior += c2v[c][COL_EDGE[v][j]];
            }
            hard[v] = u8::from(posterior < 0.0);
        }
        for c in 0..M {
            let mut s = 0u8;
            for i in 0..DC {
                s ^= hard[ROW_IDX[c][i]];
            }
            if s != 0 {
                ok = false;
                break;
            }
        }
        if ok {
            return Ok(hard);
        }
    }
    Ok(hard)
}
